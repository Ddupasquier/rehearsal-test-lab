create extension if not exists pgcrypto with schema extensions;

create schema if not exists lab_api;
create schema if not exists publication;

create type lab_api.entry_status as enum ('draft', 'active', 'archived');

create table lab_api.accounts (
  id uuid primary key,
  email text not null unique,
  display_name text not null,
  role text not null check (role in ('owner', 'developer', 'viewer')),
  avatar_path text,
  preferences jsonb not null default '{}'::jsonb,
  created_at timestamptz not null,
  updated_at timestamptz not null
);

create table lab_api.projects (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references lab_api.accounts(id) deferrable initially deferred,
  name text not null,
  slug text not null unique,
  settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null
);

create table lab_api.entries (
  id bigint generated by default as identity primary key,
  project_id bigint not null references lab_api.projects(id),
  owner_id uuid not null references lab_api.accounts(id) deferrable initially deferred,
  title text not null,
  normalized_title text generated always as (lower(title)) stored,
  amount numeric(12, 2) not null check (amount >= 0),
  status lab_api.entry_status not null,
  details jsonb not null,
  occurred_on date not null,
  created_at timestamptz not null
);

create index entries_owner_created_idx on lab_api.entries (owner_id, created_at desc);
create index entries_details_gin_idx on lab_api.entries using gin (details);

create table lab_api.audit_events (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references lab_api.accounts(id) deferrable initially deferred,
  event_type text not null,
  payload jsonb not null,
  occurred_at timestamptz not null
);

create table publication.documents (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references lab_api.accounts(id) deferrable initially deferred,
  slug text not null unique,
  title text not null,
  published_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create table publication.document_items (
  id bigint generated by default as identity primary key,
  document_id bigint not null references publication.documents(id) on delete cascade,
  position integer not null check (position > 0),
  body text not null,
  unique (document_id, position)
);

create or replace function lab_api.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = clock_timestamp();
  return new;
end;
$$;

create trigger accounts_set_updated_at
before update on lab_api.accounts
for each row execute function lab_api.set_updated_at();

alter table lab_api.accounts enable row level security;
alter table lab_api.projects enable row level security;
alter table lab_api.entries enable row level security;
alter table lab_api.audit_events enable row level security;
alter table publication.documents enable row level security;
alter table publication.document_items enable row level security;

create policy accounts_owner_read on lab_api.accounts
  for select using ((select auth.uid()) = id);
create policy accounts_rehearsal_export on lab_api.accounts
  for select using (current_user in ('rehearsal_lab_owner', 'rehearsal_lab_reader'));
create policy projects_owner_all on lab_api.projects
  for all using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy projects_rehearsal_export on lab_api.projects
  for select using (current_user in ('rehearsal_lab_owner', 'rehearsal_lab_reader'));
create policy entries_owner_all on lab_api.entries
  for all using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy entries_rehearsal_export on lab_api.entries
  for select using (current_user in ('rehearsal_lab_owner', 'rehearsal_lab_reader'));
create policy audit_owner_read on lab_api.audit_events
  for select using ((select auth.uid()) = owner_id);
create policy audit_rehearsal_export on lab_api.audit_events
  for select using (current_user in ('rehearsal_lab_owner', 'rehearsal_lab_reader'));
create policy documents_owner_all on publication.documents
  for all using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);
create policy documents_rehearsal_export on publication.documents
  for select using (current_user in ('rehearsal_lab_owner', 'rehearsal_lab_reader'));
create policy document_items_owner_read on publication.document_items
  for select using (
    exists (
      select 1 from publication.documents
      where documents.id = document_items.document_id
        and documents.owner_id = (select auth.uid())
    )
  );

