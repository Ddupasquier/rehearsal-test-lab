create schema lab_api;
create schema publication;
create schema rehearsal_migrations;

create table rehearsal_migrations.schema_migrations (
  version text primary key,
  name text not null,
  statements text[] not null
);

create table lab_api.accounts (
  id uuid primary key,
  email text not null unique,
  display_name text not null,
  created_at timestamptz not null
);

create table lab_api.entries (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references lab_api.accounts(id),
  title text not null,
  normalized_title text generated always as (lower(title)) stored,
  amount numeric(12, 2) not null check (amount >= 0),
  details jsonb not null,
  created_at timestamptz not null
);

create index entries_owner_created_idx on lab_api.entries (owner_id, created_at desc);
create index entries_details_gin_idx on lab_api.entries using gin (details);

create table publication.documents (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references lab_api.accounts(id),
  slug text not null unique,
  title text not null,
  published_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);
